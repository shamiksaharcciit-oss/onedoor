"""Publish the proposer benchmark. `python -m scripts.benchmark_proposer [--write]`.

R053 §4: **the demo gate is disclosure-shaped, not score-shaped.** The demo may run when
the benchmark's results — *misses included* — are published beside it and the demo states
its number. So this writes `docs/proposer-benchmark.md`, misses first, and a test asserts
the committed document matches what the harness currently produces.

Misses first is not a formatting preference. A report that leads with a score and buries
its failures is the disclosure that discloses the comfortable half.

CI runs the **fixture** path only — no key, no network, no spend. A live run is
credentialed, budgeted, and scheduled outside CI.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

from onedoor.studio import benchmark, proposer

DOC = Path(__file__).resolve().parent.parent / "docs" / "proposer-benchmark.md"


def render(report: dict) -> str:
    """The published document. Generated by tooling, never hand-edited (X-11)."""
    misses = report["misses"]
    lines = [
        "# Proposer benchmark — results, misses included",
        "",
        "**Generated by `python -m scripts.benchmark_proposer --write`. Do not hand-edit.**",
        "",
        "R053 §4: the demo gate is **disclosure-shaped, not score-shaped**. No threshold",
        "gates anything — *a threshold we choose for our own generator is the instrument",
        "fitted to the finding*. The rule is that the demo may run when these results,",
        "**misses included**, are published beside it and the demo states its number.",
        "",
        f"- **proposer_provenance:** `{report['proposer_provenance']}`",
        f"- **score:** {report['passed']} / {report['cases']}",
        f"- **misses:** {len(misses)} "
        f"(security {report['misses_by_kind']['security']}, "
        f"quality {report['misses_by_kind']['quality']})",
        "",
        "## Misses",
        "",
    ]
    if not misses:
        lines += [
            "None on this run. **A clean sheet is a statement about this corpus, not about",
            "the generator** — see the coverage note below for what is not measured.",
            "",
        ]
    else:
        lines.append("| case | kind | adversarial | why it missed |")
        lines.append("|---|---|---|---|")
        for miss in misses:
            why = "; ".join(miss["reasons"])
            lines.append(
                f"| `{miss['name']}` | **{miss['kind']}** | "
                f"{'yes' if miss['adversarial'] else 'no'} | {why} |"
            )
        lines.append("")

    lines += ["## Every case", "", "| case | kind | adversarial | result |", "|---|---|---|---|"]
    for result in report["results"]:
        lines.append(
            f"| `{result['name']}` | {result['kind']} | "
            f"{'yes' if result['adversarial'] else 'no'} | "
            f"{'pass' if result['passed'] else '**MISS**'} |"
        )

    lines += [
        "",
        "## The instrument",
        "",
    ]
    for key, value in sorted(report["instrument"].items()):
        lines.append(f"- **{key}:** `{value}`")

    lines += [
        "",
        "## What this does not measure",
        "",
        benchmark.coverage_note(),
        "",
        "**And the specific limit of a `fixture` run:** the shipped stand-in is a keyword",
        "matcher that draws only from the vetted pack. It never interprets instructions, so",
        "it passes the prompt-injection cases *by construction rather than by judgement* —",
        "that is a real property of the stand-in and it is **not evidence about a model**.",
        "The two misses it does produce are genuine: it cannot read a negation, and it",
        "cannot tell a description about reading money from one about moving it. Both",
        "produce over-permissive proposals, which is why one is filed as security-shaped.",
        "",
    ]
    return "\n".join(lines) + "\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(prog="python -m scripts.benchmark_proposer")
    parser.add_argument("--write", action="store_true", help=f"write {DOC.name}")
    args = parser.parse_args(argv)

    instrument = proposer.FixtureProposer()
    report = benchmark.report(benchmark.run(instrument), instrument)
    document = render(report)

    print(f"provenance: {report['proposer_provenance']}")
    print(f"score:      {report['passed']}/{report['cases']}")
    print(f"misses:     {len(report['misses'])} {report['misses_by_kind']}")
    for miss in report["misses"]:
        print(f"  MISS {miss['name']} [{miss['kind']}]: {'; '.join(miss['reasons'])}")

    if DOC.is_file() and DOC.read_text(encoding="utf-8") == document:
        print("PUBLISHED DOCUMENT IS CURRENT")
        return 0
    if not args.write:
        print("DRIFT — rerun with --write once you have looked at what changed", file=sys.stderr)
        return 1
    DOC.parent.mkdir(parents=True, exist_ok=True)
    DOC.write_text(document, encoding="utf-8", newline="\n")
    print(f"WROTE {DOC}")
    return 0


if __name__ == "__main__":  # pragma: no cover - the entry point
    raise SystemExit(main())
