"""The proposer benchmark and its published misses (S6-T6, R053 §4).

The gate is **disclosure-shaped**: no score threshold, but the published document must be
current, must lead with the misses, and must include the security-shaped ones. These tests
hold that — including the one that matters most, which is that a **clean sheet cannot be
manufactured by weakening the corpus.**
"""

from __future__ import annotations

from pathlib import Path

import pytest

from onedoor.studio import benchmark, proposer
from scripts import benchmark_proposer

DOC = Path(__file__).resolve().parents[2] / "docs" / "proposer-benchmark.md"


@pytest.fixture(scope="module")
def report() -> dict:
    instrument = proposer.FixtureProposer()
    return benchmark.report(benchmark.run(instrument), instrument)


# --- The corpus is what makes the number mean anything ----------------------------


def test_the_corpus_contains_adversarial_descriptions() -> None:
    """R053 §4 requires them by name: text crafted to talk a proposer into permissive rules."""
    adversarial = [c for c in benchmark.CORPUS if c.adversarial]
    assert len(adversarial) >= 3, "too few adversarial cases to call this a security corpus"
    for case in adversarial:
        assert case.kind == benchmark.SECURITY


def test_the_corpus_contains_security_shaped_cases_the_fixture_actually_fails() -> None:
    """**The test that stops a clean sheet being manufactured.**

    A corpus tuned until the instrument passes everything is a benchmark that measures
    nothing, and its published document would read as a perfect score. So at least one
    security-shaped case must be a real, current miss — and when the instrument improves
    enough to pass it, this test failing is the signal to make the corpus harder, not to
    delete the requirement.
    """
    instrument = proposer.FixtureProposer()
    misses = [r for r in benchmark.run(instrument) if not r.passed]
    assert misses, (
        "the corpus produces no misses at all. A benchmark whose instrument passes "
        "everything is measuring the corpus, not the instrument."
    )
    assert any(r.case.kind == benchmark.SECURITY for r in misses), (
        "no security-shaped miss. R053 §4 requires the published misses to include the "
        "security-shaped ones, and a corpus that only catches quality failures cannot."
    )


def test_every_case_declares_what_correct_looks_like() -> None:
    """A case with no expectation either way can never fail, and would pad the score."""
    for case in benchmark.CORPUS:
        has_expectation = bool(case.expect_actions or case.forbid_actions or case.note)
        assert has_expectation, f"{case.name} asserts nothing"


# --- The published document -------------------------------------------------------


def test_the_published_document_is_current(report: dict) -> None:
    """Generated by tooling, never hand-edited. Regenerate with `--write`."""
    assert DOC.is_file(), "the benchmark has never been published"
    assert DOC.read_text(encoding="utf-8") == benchmark_proposer.render(report), (
        "docs/proposer-benchmark.md has drifted. Run "
        "`python -m scripts.benchmark_proposer --write` and look at what changed."
    )


def test_the_document_leads_with_the_misses(report: dict) -> None:
    """*A report that leads with a score and buries its failures discloses the comfortable half.*"""
    text = benchmark_proposer.render(report)
    assert text.index("## Misses") < text.index("## Every case")


def test_every_miss_is_published_with_its_reason(report: dict) -> None:
    text = benchmark_proposer.render(report)
    assert report["misses"], "no misses to publish; this test would be vacuous"
    for miss in report["misses"]:
        assert miss["name"] in text
        for reason in miss["reasons"]:
            assert reason in text, f"{miss['name']}'s reason is not in the published document"


def test_the_document_states_the_provenance_and_the_number(report: dict) -> None:
    """The demo states its number, and the number is labelled with which instrument made it."""
    text = benchmark_proposer.render(report)
    assert f"`{report['proposer_provenance']}`" in text
    assert f"{report['passed']} / {report['cases']}" in text


def test_the_document_states_what_it_does_not_measure() -> None:
    """Principle 4, turned on the benchmark itself."""
    text = DOC.read_text(encoding="utf-8")
    assert "What this does not measure" in text
    assert "not evidence about a model" in text, (
        "the fixture passes the injection cases BY CONSTRUCTION, and a report that does "
        "not say so invites its score to be read as a claim about a model"
    )


def test_a_miss_reason_names_the_right_failure() -> None:
    """Over-proposing a pack rule and inventing one are different facts.

    An earlier version reported both as *"invented rules the pack does not contain"*,
    which was false for every case where the rule exists — a message that outruns its
    evidence, and a false accusation with a stack trace.
    """
    instrument = proposer.FixtureProposer()
    negation = next(c for c in benchmark.CORPUS if c.name == "negation_blind")
    result = benchmark.check(negation, instrument.propose(negation.description))
    assert not result.passed
    assert any("did not ask for" in r for r in result.reasons)
    assert not any("invented" in r for r in result.reasons), (
        "refunds.issue IS in the pack — it was over-proposed, not invented"
    )


# --- The law family, on generated output ------------------------------------------


def test_no_case_produces_a_candidate_the_engine_would_refuse() -> None:
    """Every proposal, adversarial ones included, must survive `validate_policy`.

    Not "the proposer resisted the instruction" — *nothing here relies on the model
    refusing.* This asserts the candidate is checkable and checked, which is the property
    that holds whatever the description said.
    """
    from onedoor.studio import validate

    instrument = proposer.FixtureProposer()
    for case in benchmark.CORPUS:
        proposal = instrument.propose(case.description)
        problems = validate.problems(proposal.policies, proposal.effects)
        assert problems == [], f"{case.name} produced a candidate the engine refuses: {problems}"


def test_no_case_produces_an_undeclared_effect_label() -> None:
    """Q3's law against every description in the corpus, adversarial ones included."""
    instrument = proposer.FixtureProposer()
    for case in benchmark.CORPUS:
        proposal = instrument.propose(case.description)
        declared = {e.effect for e in proposal.effects}
        named = {e for p in proposal.policies for e in p.effects}
        named |= {e for p in proposal.policies for r in p.param_effects for e in r.add_effects}
        assert not (named - declared), (
            f"{case.name} emitted a silent permit: {sorted(named - declared)}"
        )
